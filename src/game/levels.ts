const PROGRESS_KEY = 'optimum_hill_climb_progress_v2';
const WALLET_KEY = 'optimum_hill_climb_wallet_v2';

export function getInitialProgress(): ProgressMap {
  const defaults: ProgressMap = {};
  for (const lvl of LEVELS) {
    defaults[lvl.id] = {
      unlocked: lvl.id === 1,
      completed: false,
      stars: 0,
      bestDistance: 0,
      bestCoins: 0,
    };
  }
  try {
    const raw = localStorage.getItem(PROGRESS_KEY);
    if (!raw) return defaults;
    const parsed = JSON.parse(raw) as ProgressMap;
    for (const lvl of LEVELS) {
      if (parsed[lvl.id]) {
        defaults[lvl.id] = {
          ...defaults[lvl.id],
          ...parsed[lvl.id],
          unlocked: lvl.id === 1 ? true : Boolean(parsed[lvl.id].unlocked),
        };
      }
    }
  } catch {
    // ignore storage errors
  }
  return defaults;
}

export function saveProgress(progress: ProgressMap) {
  try {
    localStorage.setItem(PROGRESS_KEY, JSON.stringify(progress));
  } catch {
    // ignore
  }
}

export function getStoredWallet(): number {
  try {
    const raw = localStorage.getItem(WALLET_KEY);
    return raw ? Math.max(0, parseInt(raw, 10) || 0) : 0;
  } catch {
    return 0;
  }
}

export function saveWallet(coins: number) {
  try {
    localStorage.setItem(WALLET_KEY, Math.max(0, Math.floor(coins)).toString());
  } catch {
    // ignore
  }
}
